// Parameter binding: ?, ?NNN, :name, $name, @name, bare names, conflicts, unknown names,
// allowBare/allowUnknown via options and setters, mixed named + anonymous, value types.
import { DatabaseSync } from "node:sqlite";
import { log, attempt } from "./common.mjs";

const db = new DatabaseSync(":memory:");
const sel = (sql, ...args) => attempt(() => db.prepare(sql).get(...args));
log("anonymous", sel("SELECT ? AS a, ? AS b", 1, "two"));
log("numbered", sel("SELECT ?2 AS a, ?1 AS b", "x", "y"));
log("colon", sel("SELECT :a AS a", { ":a": 1 }));
log("dollar", sel("SELECT $a AS a", { $a: 2 }));
log("at", sel("SELECT @a AS a", { "@a": 3 }));
log("bare", sel("SELECT :a AS a, $b AS b, @c AS c", { a: 1, b: 2, c: 3 }));
log("prefixed and bare", sel("SELECT :a AS a", { ":a": 1, a: 2 }));
log("unknown", sel("SELECT :a AS a", { a: 1, z: 2 }));
log("missing named binds null", sel("SELECT :a AS a, :b AS b", { a: 1 }));
log("conflict", sel("SELECT $k AS a, @k AS b", { k: 1 }));
log("conflict prefixed", sel("SELECT $k AS a, @k AS b", { $k: 1, "@k": 2 }));
log("mixed", sel("SELECT :n AS n, ? AS a, ? AS b", { n: "named" }, 1, 2));
log("anonymous skips named", sel("SELECT ? AS a, :n AS n, ? AS b", { n: 0 }, 1, 2));
log("too many", sel("SELECT ? AS a", 1, 2));
log("too few", sel("SELECT ? AS a, ? AS b", 1));
log("named after anonymous", sel("SELECT ? AS a", 1, { a: 1 }));
log("array as named", sel("SELECT ? AS a", [1]));
log("undefined", sel("SELECT ? AS a", undefined));
log("boolean", sel("SELECT ? AS a", true));
log("symbol", sel("SELECT ? AS a", Symbol("s")));
log("function as named", sel("SELECT :a AS a", Object.assign(() => {}, { a: 1 })));
log("date", sel("SELECT ? AS a", new Date(0)));
log("bigint", sel("SELECT ? AS a, typeof(?) AS t", 5n, 5n));
log("bigint max", sel("SELECT ? AS a", 2n ** 63n - 1n));
log("bigint too large", sel("SELECT ? AS a", 2n ** 63n));
log("number kinds", sel("SELECT typeof(?) AS a, typeof(?) AS b, ? AS c, ? AS d", 1, 1.5, NaN, -0));
log("infinity", sel("SELECT ? AS a", Infinity));
log("string with nul", sel("SELECT length(?) AS n, hex(?) AS h", "a\0b", "a\0b"));
log("lone surrogate", sel("SELECT hex(?) AS h", "\ud800"));
log("unicode", sel("SELECT ? AS s, length(?) AS n", "héllo 🌍", "héllo 🌍"));
log("symbol key ignored", sel("SELECT :a AS a", { a: 1, [Symbol("x")]: 2 }));
log("non-enumerable ignored", sel("SELECT :a AS a", Object.defineProperty({}, "a", { value: 1 })));
log("inherited ignored", sel("SELECT :a AS a", Object.create({ a: 1 })));
const getterOrder = [];
log("getter", sel("SELECT :a AS a, :b AS b", { get b() { getterOrder.push("b"); return 2; }, get a() { getterOrder.push("a"); return 1; } }));
log("getter order", getterOrder);

const strict = db.prepare("SELECT :a AS a");
strict.setAllowBareNamedParameters(false);
log("bare disabled", attempt(() => strict.get({ a: 1 })));
log("bare disabled prefixed", attempt(() => strict.get({ ":a": 1 })));
const loose = db.prepare("SELECT :a AS a");
loose.setAllowUnknownNamedParameters(true);
log("unknown allowed", attempt(() => loose.get({ a: 1, z: 2 })));
log("setter type", attempt(() => loose.setAllowUnknownNamedParameters(1)));
log("setter type bare", attempt(() => loose.setAllowBareNamedParameters("yes")));
const optsDb = new DatabaseSync(":memory:", { allowBareNamedParameters: false, allowUnknownNamedParameters: true });
log("options bare off", attempt(() => optsDb.prepare("SELECT :a AS a").get({ a: 1 })));
log("options unknown on", attempt(() => optsDb.prepare("SELECT :a AS a").get({ ":a": 1, z: 1 })));
const conflictStmt = db.prepare("SELECT $k AS a, @k AS b");
log("conflict first", attempt(() => conflictStmt.get({ k: 1 })));
log("conflict cached", attempt(() => conflictStmt.get({ k: 1 })));
const reused = db.prepare("SELECT :a AS a, ? AS b");
log("rebinding clears", [reused.get({ a: 1 }, 2), reused.get({}), reused.get()]);
log("expandedSQL", (() => { const s = db.prepare("SELECT :a, $b, ?, @c"); s.get({ a: "it's", b: 1.25, c: new Uint8Array([1, 255]) }, 7n); return s.expandedSQL; })());
log("expandedSQL unbound", db.prepare("SELECT ?, :x").expandedSQL);
log("sourceSQL", db.prepare("  SELECT 1  ").sourceSQL);
db.close();
