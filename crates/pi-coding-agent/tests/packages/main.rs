//! Package smoke harness (PKGP-01): the pinned third-party Pi packages load on pi-rs and register
//! the same tools and commands as on TS Pi 1.4.0.
//!
//! Each scenario starts the `pi` binary in print mode and in RPC mode inside an isolated `HOME`
//! and `PI_CODING_AGENT_DIR`, next to the scripted mock model `tests/fixtures/mock/mockllm.py`,
//! in an empty network namespace where the platform allows it. Any extension-error diagnostic
//! fails the scenario.
//!
//! The package scenarios need the fixtures fetched once with `scripts/package-fixtures.sh`; they
//! are skipped unless `PI_RS_PKG_FIXTURES` is set:
//!
//! ```text
//! scripts/package-fixtures.sh
//! PI_RS_PKG_FIXTURES=1 cargo test -p pi-coding-agent --test packages
//! ```
//!
//! The golden (`tests/fixtures/packages/golden/ts-pi-1.4.0.json`) is regenerated by
//! `scripts/package-golden.sh`, which runs these same scenarios against TS Pi 1.4.0 under node.

