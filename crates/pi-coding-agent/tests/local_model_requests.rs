//! Golden openai-completions request bodies for local llama.cpp / NInfer model entries.
//!
//! `fixtures/local_models/models.json` holds six provider entries shaped like a daily local
//! setup (four NInfer entries with `thinkingLevelMap` and `compat.supportsReasoningEffort`, two
//! llama.cpp entries without compat; two with a trailing-slash `baseUrl`). Each one is loaded
//! through the model runtime and sent `context.json` (a replayed llama.cpp tool turn with
//! `reasoning_content`, two tool calls, one with float arguments, and an image tool result for a
//! text-only model) at every thinking level. The bodies must match, byte for byte (key order and
//! number formatting included), what TS Pi 1.4.0 sends for the same input:
//! `request_bodies.json` is generated by `scripts/golden/local-model-requests.mjs`.

#[path = "../../pi-ai/tests/mock_http/mod.rs"]
mod mock_http;

use std::path::PathBuf;
use std::sync::Arc;

use mock_http::{MockServer, Request, Response};
use pi_ai::models::ModelsRequestOptions;
use pi_ai::providers::model_schema::ThinkingLevel;
use pi_ai::types::{Context, StopReason, StreamOptions};
use pi_coding_agent::core::auth_storage::AuthStorage;
use pi_coding_agent::core::model_registry::ModelRegistry;
use pi_coding_agent::core::model_runtime::{CreateModelRuntimeOptions, ModelRuntime};
use pi_coding_agent::core::models_store::InMemoryCodingAgentModelsStore;
use serde::Deserialize;
use serde_json::{Value, json};

#[derive(Deserialize)]
struct Golden {
    #[serde(rename = "apiKey")]
    api_key: String,
    cases: Vec<GoldenCase>,
}

#[derive(Deserialize)]
struct GoldenCase {
    provider: String,
    model: String,
    level: String,
    path: String,
    body: String,
}

fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/local_models")
}

fn read_fixture(name: &str) -> String {
    std::fs::read_to_string(fixtures().join(name)).unwrap_or_else(|e| panic!("{name}: {e}"))
}

fn thinking_level(level: &str) -> Option<ThinkingLevel> {
    match level {
        "off" => None,
        other => Some(serde_json::from_value(json!(other)).unwrap_or_else(|e| panic!("level {other}: {e}"))),
    }
}

fn stop_chunk() -> Response {
    let chunk = json!({"id": "chatcmpl-local", "object": "chat.completion.chunk", "model": "m",
                       "choices": [{"index": 0, "delta": {"content": "ok"}, "finish_reason": "stop"}]});
    Response::sse(&format!("data: {chunk}\n\ndata: [DONE]\n\n"))
}

#[tokio::test]
async fn local_model_request_bodies_match_ts_pi() {
    let golden: Golden = serde_json::from_str(&read_fixture("request_bodies.json")).unwrap();
    assert_eq!(golden.cases.len(), 6 * 7, "six entries at seven thinking levels");
    let server = MockServer::start(|_request: &Request, _| stop_chunk()).await;

    let dir = tempfile::tempdir().unwrap();
    let mut models: Value = serde_json::from_str(&read_fixture("models.json").replace("{{BASE_URL}}", &server.url)).unwrap();
    for provider in models["providers"].as_object_mut().unwrap().values_mut() {
        provider["apiKey"] = json!(golden.api_key);
    }
    let models_path = dir.path().join("models.json");
    std::fs::write(&models_path, serde_json::to_string_pretty(&models).unwrap()).unwrap();
    let runtime = ModelRuntime::create(Some(&CreateModelRuntimeOptions {
        credentials: Some(AuthStorage::create(Some(&dir.path().join("auth.json").to_string_lossy()))),
        models_path: Some(models_path.to_string_lossy().into_owned()),
        models_store: Some(Arc::new(InMemoryCodingAgentModelsStore::new())),
        allow_model_network: Some(false),
        ..Default::default()
    }))
    .await
    .unwrap();
    let registry = ModelRegistry::new(runtime.clone());
    let context_template = read_fixture("context.json");

    let mut mismatches = Vec::new();
    for (index, case) in golden.cases.iter().enumerate() {
        let label = format!("{}/{}@{}", case.provider, case.model, case.level);
        let model = registry.find(&case.provider, &case.model).unwrap_or_else(|| panic!("{label}: model not loaded"));
        let context: Context = serde_json::from_str(
            &context_template.replace("{{PROVIDER}}", &case.provider).replace("{{MODEL}}", &case.model),
        )
        .unwrap();
        let options = StreamOptions { reasoning: thinking_level(&case.level), ..Default::default() };
        let result = runtime.stream_simple(model, context, Some(ModelsRequestOptions::from(options))).result().await;
        assert_eq!(result.stop_reason, StopReason::Stop, "{label}: {:?}", result.error_message);
        let request = server.request(index);
        assert_eq!(request.path, case.path, "{label}");
        let body = request.text();
        if body != case.body {
            mismatches.push(format!("{label}\n  ts:   {}\n  rust: {body}", case.body));
        }
    }
    assert!(mismatches.is_empty(), "{} of {} bodies differ from TS Pi:\n{}", mismatches.len(), golden.cases.len(), mismatches.join("\n"));
}
